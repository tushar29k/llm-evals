"""Build evals/adversarial-report.md from fresh runs of every suite.

Deterministic: the mock judge is deterministic, the probes are fixed
strings, and the report carries no timestamps — regenerating it after
any change diffs only where the numbers actually moved.

    python evals/make_report.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import run_adversarial  # noqa: E402
import run_bias_probes  # noqa: E402
import scoring  # noqa: E402
from llm_evals.judge import Judge, measure_agreement  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "adversarial-report.md")
ROOT = os.path.dirname(HERE)


def pct(x):
    return "n/a" if x is None else f"{x:.1%}"


def suite_row(name, agg):
    a, b = agg["attacks"], agg["benign"]
    return (
        f"| {name} | {a['n']} | {a['blocked']} | {a['succeeded']} | "
        f"{a['evaded']} | {pct(a['asr'])} | {b['n']} | {pct(b['frr'])} | "
        f"{pct(agg['decision_accuracy'])} |"
    )


def main():
    judge = Judge(threshold=run_adversarial.THRESHOLD)
    seed_out = run_adversarial.run_suite("seeds", judge)
    var_out = run_adversarial.run_suite("variants", judge)
    seed_agg = scoring.aggregate(seed_out)
    var_agg = scoring.aggregate(var_out)

    # per-mutation table over the variant attacks
    by_mut = {}
    for case, outcome, cls in var_out:
        if case["kind"] != "attack":
            continue
        by_mut.setdefault(case["mutation"], []).append((case, outcome, cls))
    mut_rows = []
    for name in sorted(by_mut):
        rows = by_mut[name]
        n = len(rows)
        succ = sum(1 for _, _, k in rows if k == "succeeded")
        blocked = sum(1 for _, _, k in rows if k == "blocked")
        evaded = sum(1 for _, _, k in rows if k == "evaded")
        mut_rows.append(
            f"| {name} | {n} | {blocked} | {succ} | {evaded} | {pct(succ / n)} |")

    length = run_bias_probes.length_ladder(judge)
    order = run_bias_probes.order_probes(judge)
    wording = run_bias_probes.wording_ladder(judge)

    _, benign_summary = measure_agreement(
        os.path.join(ROOT, "datasets", "judge_agreement.jsonl"))
    _, slice_summary = measure_agreement(
        os.path.join(HERE, "agreement_slice.jsonl"))

    lines = [
        "# Adversarial report — the scoring pipeline under attack",
        "",
        "Generated by `evals/make_report.py` from the checked-in suites "
        "(`adversarial_seeds.jsonl`, `adversarial_variants.jsonl`, "
        "`agreement_slice.jsonl`) against the default mock judge at the "
        "standard 0.8 threshold. Metric definitions are frozen in "
        "`evals/scoring.py` (v1). Report-only: nothing here gates CI.",
        "",
        "## Suite summary",
        "",
        "| suite | attacks | blocked | succeeded | evaded | ASR | benign (n) | FRR | decision accuracy |",
        "|---|---|---|---|---|---|---|---|---|",
        suite_row("seeds", seed_agg),
        suite_row("variants", var_agg),
        "",
        f"Mean judge-avg inflation vs each attack's clean_output: "
        f"seeds {seed_agg['attacks']['mean_inflation']:+.3f} "
        f"(n={seed_agg['attacks']['inflation_n']}), variants "
        f"{var_agg['attacks']['mean_inflation']:+.3f} "
        f"(n={var_agg['attacks']['inflation_n']}). Negative on variants: "
        "surface mutations mostly *weaken* attacks against a keyword "
        "judge — they destroy the keyword overlap the attack was riding.",
        "",
        "## Per-mutation results (variant attacks)",
        "",
        "| mutation | runs | blocked | succeeded | evaded | ASR |",
        "|---|---|---|---|---|---|",
        *mut_rows,
        "",
        "## Bias probes",
        "",
        "Length ladder — the reference answer itself, padded. Repetition "
        "freezes the token set (only the clarity rule can move); neutral "
        "sentences dilute keyword precision.",
        "",
        "| padding | words | correctness | completeness | clarity | avg |",
        "|---|---|---|---|---|---|",
        *[
            f"| {pad} | {n} | {s['correctness']} | {s['completeness']} | "
            f"{s['clarity']} | {avg:.3f} |"
            for pad, n, s, avg in length
        ],
        "",
        "Order probes — same tokens, three orders:",
        "",
        "| order | correctness | completeness | clarity | avg |",
        "|---|---|---|---|---|",
        *[
            f"| {name} | {s['correctness']} | {s['completeness']} | "
            f"{s['clarity']} | {avg:.3f} |"
            for name, s, avg in order
        ],
        "",
        "Wording ladder — same fact, decreasing keyword overlap:",
        "",
        "| wording | correctness | completeness | clarity | avg |",
        "|---|---|---|---|---|",
        *[
            f"| {name} | {s['correctness']} | {s['completeness']} | "
            f"{s['clarity']} | {avg:.3f} |"
            for name, s, avg in wording
        ],
        "",
        "## Judge-vs-human agreement: benign set vs adversarial slice",
        "",
        "Both sets are human-labelled cases in the repo's agreement "
        "format, graded by `measure_agreement` with the same mock judge. "
        "The benign set is `datasets/judge_agreement.jsonl` (12 cases); "
        "the slice is `evals/agreement_slice.jsonl` (10 cases, half of "
        "them attack outputs with human labels).",
        "",
        "| set | cases | exact | within-1 | MAE | decision agreement |",
        "|---|---|---|---|---|---|",
        f"| benign (judge_agreement) | {benign_summary['cases']} | "
        f"{benign_summary['exact_agreement']:.3f} | "
        f"{benign_summary['within1_agreement']:.3f} | "
        f"{benign_summary['mae']:.3f} | "
        f"{benign_summary['decision_agreement']:.3f} |",
        f"| adversarial slice | {slice_summary['cases']} | "
        f"{slice_summary['exact_agreement']:.3f} | "
        f"{slice_summary['within1_agreement']:.3f} | "
        f"{slice_summary['mae']:.3f} | "
        f"{slice_summary['decision_agreement']:.3f} |",
        "",
        "## Per-case detail (seeds)",
        "",
        "| case | kind/class | avg | clean avg | outcome |",
        "|---|---|---|---|---|",
        *[
            f"| {c['id']} | {c['kind']}"
            f"{'/' + c['attack_class'] if c.get('attack_class') else ''} | "
            f"{o['avg'] if o.get('avg') is not None else '—'} | "
            f"{o['clean_avg'] if o.get('clean_avg') is not None else '—'} | "
            f"{k} |"
            for c, o, k in seed_out
        ],
        "",
    ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
